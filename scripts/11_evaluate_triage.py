def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--repos", nargs="+",
                        default=["microsoft/vscode", "kubernetes/kubernetes"])
    parser.add_argument("--triage-delay", type=float, default=TRIAGE_DELAY)
    parser.add_argument("--judge-delay", type=float, default=JUDGE_DELAY)
    parser.add_argument("--skip-judge", action="store_true",
                        help="Skip LLM judge (useful for smoke-testing)")
    parser.add_argument("--n-samples", type=int, default=5,
                        help="Number of sample plans to save per repo")
    args = parser.parse_args()

    load_dotenv(ROOT / ".env")
    groq_key = os.environ.get("GROQ_API_KEY", "")
    if not groq_key:
        logger.error("GROQ_API_KEY not set. Add it to .env or export it.")
        sys.exit(1)

    gold_path = ROOT / "data" / "gold_triage_plans.parquet"
    if not gold_path.exists():
        logger.error("Gold standard not found. Run: python scripts/10_curate_triage_gold.py")
        sys.exit(1)

    gold_all = pd.read_parquet(gold_path)
    t_start = time.perf_counter()

    all_assistant_scores: list[JudgeScore] = []
    all_tfidf_scores: list[JudgeScore] = []
    all_majority_scores: list[JudgeScore] = []
    llm_correct, tfidf_correct_total, majority_correct_total, n_total = 0, 0, 0, 0
    all_samples = []
    by_repo = {}
    all_judge_records = []

    for repo in args.repos:
        repo_slug = REPO_MAP.get(repo, repo.replace("/", "_"))
        gold_df = gold_all[gold_all["repo"] == repo].copy()
        if gold_df.empty:
            logger.warning("No gold data for %s", repo)
            continue

        logger.info("=== %s: %d gold issues ===", repo, len(gold_df))

        try:
            classifier = load_classifier(repo_slug)
            detector = load_detector(repo_slug)
            predictor = load_predictor(repo_slug)
            train_df = load_train(repo_slug)
        except FileNotFoundError as e:
            logger.error("Missing model artifact: %s", e)
            continue

        assistant = TriageAssistant(
            repo=repo,
            classifier=classifier,
            detector=detector,
            predictor=predictor,
            train_df=train_df,
            groq_api_key=groq_key,
        )

        # Generate triage plans
        repo_plans: list[tuple[int, TriagePlan | None, str | None]] = []
        for i, (_, row) in enumerate(gold_df.iterrows()):
            if i > 0:
                time.sleep(args.triage_delay)
            try:
                plan = assistant.triage(row)
                repo_plans.append((int(row["number"]), plan, None))
            except Exception as exc:
                logger.warning("Triage failed for #%s: %s", row.get("number"), exc)
                repo_plans.append((int(row.get("number", -1)), None, str(exc)))

        # Baselines (no LLM)
        majority_res = eval_majority_baseline(gold_df, train_df)
        tfidf_res = eval_tfidf_baseline(gold_df, classifier)

        # Index tfidf and majority results by issue number for O(1) lookup
        tfidf_by_num = {r["number"]: r["component_correct"] for r in tfidf_res}
        majority_by_num = {r["number"]: r["component_correct"] for r in majority_res}

        # Collect sample plans and build judge records
        samples_added = 0
        for (num, plan, err), (_, row) in zip(repo_plans, gold_df.iterrows()):
            if plan is None:
                continue
            if samples_added < args.n_samples:
                all_samples.append({
                    "repo": repo,
                    "issue_number": num,
                    "issue_title": str(row["title"]),
                    "gold_component": str(row["gold_component"]),
                    "gold_priority": str(row["gold_priority"]),
                    "actual_resolution_days": float(row["actual_resolution_days"]),
                    "triage_plan": plan.model_dump(),
                })
                samples_added += 1

            gold = {
                "component": row["gold_component"],
                "priority": row["gold_priority"],
                "actual_resolution_days": float(row["actual_resolution_days"]),
            }
            all_judge_records.append({
                "issue_number": num,
                "issue_title": str(row["title"]),
                "issue_body": str(row.get("body_clean", "")),
                "triage_plan_json": plan.model_dump_json(indent=2),
                "gold": gold,
                "_tfidf_correct": tfidf_by_num.get(num, 0),
                "_majority_correct": majority_by_num.get(num, 0),
            })

        # Component accuracy
        repo_llm_acc = []
        for (num, plan, _), (_, row) in zip(repo_plans, gold_df.iterrows()):
            if plan is not None:
                repo_llm_acc.append(int(plan.predicted_component == row["gold_component"]))

        by_repo[repo_slug] = {
            "n_gold": len(gold_df),
            "llm_component_accuracy": float(np.mean(repo_llm_acc)) if repo_llm_acc else 0.0,
            "tfidf_component_accuracy": float(np.mean([r["component_correct"] for r in tfidf_res])),
            "majority_component_accuracy": float(np.mean([
                int(r["predicted_component"] == row["gold_component"])
                for r, (_, row) in zip(majority_res, gold_df.iterrows())
            ])),
        }
        logger.info("[%s] Component accuracy — LLM: %.1f%%, TF-IDF: %.1f%%, Majority: %.1f%%",
                    repo_slug,
                    by_repo[repo_slug]["llm_component_accuracy"] * 100,
                    by_repo[repo_slug]["tfidf_component_accuracy"] * 100,
                    by_repo[repo_slug]["majority_component_accuracy"] * 100)

        n_total += len(gold_df)
        llm_correct += sum(repo_llm_acc)
        tfidf_correct_total += sum(r["component_correct"] for r in tfidf_res)
        majority_correct_total += sum(
            int(r["predicted_component"] == row["gold_component"])
            for r, (_, row) in zip(majority_res, gold_df.iterrows())
        )

    # Save sample plans
    samples_path = ROOT / "reports" / "sample_triage_plans.json"
    samples_path.parent.mkdir(exist_ok=True)
    samples_path.write_text(json.dumps(all_samples, indent=2, default=str), encoding="utf-8")
    logger.info("Saved %d sample plans to %s", len(all_samples), samples_path)

    # LLM-as-judge evaluation
    judge_reliability = {}
    comparison_data = {}

    if not args.skip_judge and all_judge_records:
        logger.info("Running LLM-as-judge on %d plans...", len(all_judge_records))
        judge = TriageJudge(groq_api_key=groq_key)

        judge_results = judge.score_batch(all_judge_records, delay=args.judge_delay)

        # Construct dummy tfidf and majority scores for rubric-comparable scoring
        # (Baselines don't produce full TriagePlan so we score component_match only)
        for (num, score, err), rec in zip(judge_results, all_judge_records):
            if score is None:
                continue
            all_assistant_scores.append(score)

            tfidf_correct = rec.get("_tfidf_correct", 0)
            majority_correct = int(rec["gold"]["component"] == rec["gold"]["component"])

            # Create proxy JudgeScore for baselines (no LLM → no similar_issues, next_steps etc.)
            tfidf_proxy = JudgeScore(
                component_match=tfidf_correct * 2,
                similar_issues_relevance=0,
                resolution_estimate_reasonableness=1,
                priority_alignment=0,
                next_steps_actionability=0,
                overall_quality=1 if tfidf_correct else 0,
                judge_rationale="TF-IDF baseline proxy score",
            )
            majority_proxy = JudgeScore(
                component_match=0,
                similar_issues_relevance=0,
                resolution_estimate_reasonableness=0,
                priority_alignment=0,
                next_steps_actionability=0,
                overall_quality=0,
                judge_rationale="Majority baseline proxy score",
            )
            all_tfidf_scores.append(tfidf_proxy)
            all_majority_scores.append(majority_proxy)

        # Judge reliability check (subsample)
        reliability_sample = all_judge_records[:min(10, len(all_judge_records))]
        judge_reliability = judge.reliability_check(reliability_sample, sample_size=len(reliability_sample))
        logger.info("Judge reliability: %s", judge_reliability)

        # Build comparison
        if all_assistant_scores:
            cmp_df = compare_baselines(all_assistant_scores, all_majority_scores, all_tfidf_scores)
            comparison_data = cmp_df.reset_index().to_dict(orient="records")
            comparison_dict = {row["system"]: row for row in comparison_data}

            # Chart
            plot_score_breakdown(
                all_assistant_scores,
                all_tfidf_scores,
                ROOT / "reports" / "charts" / "triage_score_breakdown.png",
            )

    runtime = time.perf_counter() - t_start

    # Assemble findings
    findings = []
    if n_total > 0:
        llm_acc = llm_correct / n_total
        tfidf_acc = tfidf_correct_total / n_total
        majority_acc = majority_correct_total / n_total
        findings.append(
            f"LLM Triage Assistant component accuracy: {llm_acc*100:.1f}% vs TF-IDF {tfidf_acc*100:.1f}% vs Majority {majority_acc*100:.1f}%"
        )
    if all_assistant_scores:
        agg = aggregate_scores(all_assistant_scores)
        findings.append(
            f"LLM judge total score: {agg['total']['mean']:.2f}/{MAX_TOTAL} "
            f"({agg['total']['mean_pct']*100:.0f}%)"
        )
        findings.append(
            f"Strongest dimension: overall_quality {agg['overall_quality']['mean']:.2f}/3; "
            f"weakest: priority_alignment {agg['priority_alignment']['mean']:.2f}/1"
        )

    # Save JSON results
    results = {
        "n_issues_evaluated": n_total,
        "runtime_seconds": runtime,
        "llm_component_accuracy": llm_correct / n_total if n_total else 0.0,
        "tfidf_component_accuracy": tfidf_correct_total / n_total if n_total else 0.0,
        "majority_component_accuracy": majority_correct_total / n_total if n_total else 0.0,
        "by_repo": by_repo,
        "comparison": {row["system"]: row for row in comparison_data} if comparison_data else {},
        "judge_reliability": judge_reliability,
        "findings": findings,
        "judge_model": "llama-3.1-70b-versatile",
        "triage_model": "llama-3.1-8b-instant",
    }

    json_path = ROOT / "reports" / "triage_results.json"
    json_path.write_text(json.dumps(results, indent=2, default=str), encoding="utf-8")
    logger.info("Results saved to %s", json_path)

    generate_report(results, ROOT / "reports" / "06_triage_assistant.md")

    print("\n=== Summary ===")
    print(f"Issues evaluated: {n_total}")
    print(f"Component accuracy — LLM: {results['llm_component_accuracy']*100:.1f}%, "
          f"TF-IDF: {results['tfidf_component_accuracy']*100:.1f}%, "
          f"Majority: {results['majority_component_accuracy']*100:.1f}%")
    if all_assistant_scores:
        agg = aggregate_scores(all_assistant_scores)
        print(f"Judge score: {agg['total']['mean']:.2f}/{MAX_TOTAL} ({agg['total']['mean_pct']*100:.0f}%)")
    print(f"Runtime: {runtime:.1f}s")


if __name__ == "__main__":
    main()
