"""End-to-end evaluation of System 4: LLM Triage Assistant.

Pipeline:
  1. Load gold standard (data/gold_triage_plans.parquet)
  2. Load all system components (classifier, detector, predictor) per repo
  3. Generate triage plans for each gold issue (System 4 + 2 baselines)
  4. Judge all plans via LLM-as-judge (llama-3.1-70b-versatile)
  5. Check judge reliability (double-run on 10 samples)
  6. Save:
     - reports/triage_results.json   — aggregated metrics + per-issue scores
     - reports/sample_triage_plans.json — 5 sample plans per repo
     - reports/06_triage_assistant.md (generated by this script)
     - reports/charts/triage_score_breakdown.png
"""

import argparse
import json
import logging
import os
import sys
import time
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from dotenv import load_dotenv

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "src"))

from triage_iq.models.component_classifier import TFIDFComponentClassifier
from triage_iq.models.duplicates import DuplicateDetector
from triage_iq.models.resolution import ResolutionTimePredictor
from triage_iq.models.triage import TriageAssistant, TriagePlan
from triage_iq.evaluation.triage_eval import (
    TriageJudge, JudgeScore, aggregate_scores, compare_baselines,
    majority_component_baseline, tfidf_only_baseline, retrieval_only_baseline,
    DIMENSION_MAX, MAX_TOTAL,
)

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
logger = logging.getLogger(__name__)

REPO_MAP = {
    "microsoft/vscode": "microsoft_vscode",
    "kubernetes/kubernetes": "kubernetes_kubernetes",
}

# LLM rate limits (Groq free tier): delay between requests
TRIAGE_DELAY = 1.2   # seconds between triage calls
JUDGE_DELAY = 1.5    # seconds between judge calls


# ---------------------------------------------------------------------------
# Loading helpers
# ---------------------------------------------------------------------------

def load_classifier(repo_slug: str) -> TFIDFComponentClassifier:
    for prefix in ["component_classifier", "tfidf_classifier"]:
        path = ROOT / "data" / "models" / f"{prefix}_{repo_slug}.pkl"
        if path.exists():
            return TFIDFComponentClassifier.load(str(path))
    raise FileNotFoundError(f"No classifier found for {repo_slug}")


def load_detector(repo_slug: str, model_key: str = "bge") -> DuplicateDetector:
    path = ROOT / "data" / "models" / f"dup_index_{repo_slug}_{model_key}"
    if not Path(path).exists():
        raise FileNotFoundError(f"Detector not found: {path}")
    return DuplicateDetector.load(str(path))


def load_predictor(repo_slug: str) -> ResolutionTimePredictor:
    path = ROOT / "data" / "models" / f"resolution_predictor_{repo_slug}.pkl"
    if not path.exists():
        raise FileNotFoundError(f"Predictor not found: {path}")
    return ResolutionTimePredictor.load(str(path))


def load_train(repo_slug: str) -> pd.DataFrame:
    for suffix in ["temporal_train", "classifier_train", "train"]:
        path = ROOT / "data" / "processed" / f"{repo_slug}_{suffix}.parquet"
        if path.exists():
            return pd.read_parquet(path)
    raise FileNotFoundError(f"No train split found for {repo_slug}")


# ---------------------------------------------------------------------------
# Baseline evaluation (rule-based, no LLM)
# ---------------------------------------------------------------------------

def eval_majority_baseline(gold_df: pd.DataFrame, train_df: pd.DataFrame) -> list[dict]:
    """Returns per-issue dicts for majority component baseline."""
    top = train_df["component"].value_counts().idxmax()
    results = []
    for _, row in gold_df.iterrows():
        correct = int(top == row["gold_component"])
        results.append({
            "number": int(row["number"]),
            "predicted_component": top,
            "component_correct": correct,
        })
    return results


def eval_tfidf_baseline(gold_df: pd.DataFrame, classifier) -> list[dict]:
    results = []
    for _, row in gold_df.iterrows():
        pred = tfidf_only_baseline(row, classifier)
        correct = int(pred["predicted_component"] == row["gold_component"])
        results.append({
            "number": int(row["number"]),
            "predicted_component": pred["predicted_component"],
            "component_correct": correct,
            "component_confidence": pred.get("component_confidence", 0.0),
        })
    return results


def eval_llm_component_accuracy(
    repo_plans: list[tuple], gold_df: pd.DataFrame
) -> list[int]:
    """Return per-issue 0/1 correctness for LLM component prediction."""
    result = []
    for (num, plan, _), (_, row) in zip(repo_plans, gold_df.iterrows()):
        if plan is not None:
            result.append(int(plan.predicted_component == row["gold_component"]))
    return result


# ---------------------------------------------------------------------------
# LLM-as-judge scoring for a single plan
# ---------------------------------------------------------------------------

def score_plan_with_judge(
    judge: TriageJudge,
    issue: pd.Series,
    plan: TriagePlan,
) -> JudgeScore:
    gold = {
        "component": issue["gold_component"],
        "priority": issue["gold_priority"],
        "actual_resolution_days": float(issue["actual_resolution_days"]),
    }
    return judge.score(
        issue_title=str(issue["title"]),
        issue_body=str(issue.get("body_clean", "")),
        triage_plan_json=plan.model_dump_json(indent=2),
        gold=gold,
    )


# ---------------------------------------------------------------------------
# Plotting
# ---------------------------------------------------------------------------

def plot_score_breakdown(
    assistant_scores: list[JudgeScore],
    tfidf_scores: list[JudgeScore],
    out_path: Path,
) -> None:
    dims = list(DIMENSION_MAX.keys())
    dim_labels = [d.replace("_", "\n") for d in dims]

    assistant_means = [np.mean([getattr(s, d) for s in assistant_scores]) for d in dims]
    tfidf_means = [np.mean([getattr(s, d) for s in tfidf_scores]) for d in dims]
    maxes = [DIMENSION_MAX[d] for d in dims]

    x = np.arange(len(dims))
    width = 0.35

    fig, ax = plt.subplots(figsize=(12, 5))
    ax.bar(x - width / 2, assistant_means, width, label="LLM Triage Assistant", color="#2196F3")
    ax.bar(x + width / 2, tfidf_means, width, label="TF-IDF Only Baseline", color="#FF9800", alpha=0.8)

    # Draw max line per dimension
    for i, m in enumerate(maxes):
        ax.plot([i - width, i + width], [m, m], "k--", linewidth=0.8, alpha=0.4)

    ax.set_xticks(x)
    ax.set_xticklabels(dim_labels, fontsize=9)
    ax.set_ylabel("Mean Score")
    ax.set_title("LLM Triage Assistant vs TF-IDF Baseline — Judge Scores by Dimension")
    ax.legend()
    ax.set_ylim(0, max(maxes) + 0.5)

    plt.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(out_path, dpi=150)
    plt.close()
    logger.info("Saved chart to %s", out_path)


